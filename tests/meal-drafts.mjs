import assert from 'node:assert/strict';
import { createMealDrafts } from '../app/meal-drafts.js';
const values=new Map();
const storage={setItem:(key,value)=>values.set(key,value),getItem:key=>values.get(key)||null,removeItem:key=>values.delete(key)};
const a=createMealDrafts('a',{storage,indexedDB:null});
const b=createMealDrafts('b',{storage,indexedDB:null});
await a.save('meal',{description:'A',percentage:50,requestId:'keep-on-restore'});
assert.equal((await a.read('meal')).percentage,50);
assert.equal(await b.read('meal'),null);
assert.equal((await a.read('meal')).requestId,'keep-on-restore');
const pending=a.save('meal',{description:'latest'});
const removed=a.remove('meal');
await Promise.all([pending,removed]);
assert.equal(await a.read('meal'),null,'Save followed by removal cannot revive a submitted draft');
await a.save('meal',{description:'new'});
assert.equal((await a.read('meal')).description,'new');
await assert.rejects(a.save('photo',{description:'sample',photo:new File(['a'],'a.jpg')}),/cannot preserve draft photos/);
const restored=await a.read('photo');
assert.equal(restored.description,'sample','Text survives even when photo storage is unavailable');
assert.equal(restored.photo,undefined);
const blocked=createMealDrafts('blocked',{storage:null,indexedDB:null});
await assert.rejects(blocked.save('meal',{description:'x'}),/unavailable/);
console.log('Device drafts: user isolation, restore, save/remove ordering, fallback text, unavailable-photo warning passed.');
