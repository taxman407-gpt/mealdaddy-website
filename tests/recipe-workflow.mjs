import assert from 'node:assert/strict';
import {parseAmount,parseIngredients,ingredientLines,buildShoppingRows,purchaseAmount,shoppingText,sourceLink,escapeHtml} from '../app/recipe-workflow-core.mjs';
let assertions=0;
const check=(actual,expected)=>{assert.deepEqual(actual,expected);assertions++;};
check(parseAmount('1 1/2 cups').quantity,1.5);
check(parseAmount('1/0 cup').quantity,null);
check(parseAmount('1-2 tbsp').quantity,null);
check(parseAmount('1 cup, chopped').quantity,null);
check(parseAmount('to taste').quantity,null);
const source=(id,amount,unit='')=>({id,title:`Dish ${id}`,description:'Confirmed ingredients',servings:2,baseServings:2,ingredients:[{item:'Onion',amount:`${amount} ${unit}`.trim()}],active:true});
let rows=buildShoppingRows([source('a',1),source('b',2)]);
check(rows.length,1);check(rows[0].needed,3);check(rows[0].sourceIds,['a','b']);
rows[0].onHand='1';check(purchaseAmount(rows[0]),'2');
rows[0].override='Buy 1 bag';rows[0].checked=true;
let updated=buildShoppingRows([source('a',2),source('b',2)],rows);
check(updated[0].override,'Buy 1 bag');check(updated[0].checked,true);check(updated[0].review,true);
check(buildShoppingRows([source('a',1,'cup'),source('b',100,'g')]).length,2);
check(buildShoppingRows([source('a','to taste'),source('b','to taste')]).length,2);
check(buildShoppingRows([{...source('a',1),servings:4}])[0].needed,2);
check(buildShoppingRows([source('a',2)],updated)[0].needed,2);
check(buildShoppingRows([],updated)[0].retired,true);
const manual={key:'manual',manual:true,item:'Soap',needed:null,original:'',sourceIds:[],onHand:'',override:'1 bottle'};
check(buildShoppingRows([], [manual])[0].manual,true);
check(sourceLink('https://example.test/app/app.html?checkout=success#old','recipe-123'),'https://example.test/app/app.html?view=more#shopping-source=recipe-123');
const text=shoppingText({title:'List',sources:[source('a',1),source('b',2)],rows,dirty:true},'https://example.test/app/app.html');
assert(text.includes('SOURCE CHANGES PENDING'));assert(text.includes('Dish a'));assert(text.includes('shopping-source=a'));assert(text.includes('does not update MealDaddy'));assertions+=4;
check(parseIngredients(ingredientLines([{amount:'2',item:'Onion'},{amount:'',item:'Pepper'}])),[{amount:'2',item:'Onion'},{amount:'',item:'Pepper'}]);
check(escapeHtml('<img src=x onerror=alert(1)>'),'&lt;img src=x onerror=alert(1)&gt;');
assert.throws(()=>buildShoppingRows([{...source('a',1),servings:0}]));assertions++;
assert.throws(()=>purchaseAmount({...rows[0],override:'',onHand:'-2'}));assertions++;
console.log(`PASS: ${assertions} recipe/shopping logic checks`);
